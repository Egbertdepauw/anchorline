#!/usr/bin/env bash
# Moves the vendored libdivecomputer to <commit>: the only way
# third_party/libdivecomputer/ ever changes. The tree always equals
# "pinned commit + patches/*.patch". Leaves the diff for review.
#
# Usage: tool/update_upstream.sh <commit>
# Environment: SKIP_FFIGEN=1 skips the bindings step (check_vendor.sh).
set -euo pipefail

if [ $# -ne 1 ]; then
  echo "usage: $0 <commit>" >&2
  exit 2
fi
commit="$1"
if ! printf '%s' "$commit" | grep -Eq '^[0-9a-f]{40}$'; then
  echo "commit must be the full 40-character lower-case hex hash" >&2
  exit 2
fi

root="$(cd "$(dirname "$0")/.." && pwd)"
url="https://github.com/libdivecomputer/libdivecomputer.git"
dest="$root/third_party/libdivecomputer"

# Every patch needs a status line in UPSTREAM before it can be applied, so a
# forgotten line fails here rather than after the tree was replaced.
patches=()
for p in "$root"/patches/*.patch; do
  [ -e "$p" ] || continue
  patches+=("$p")
  name="$(basename "$p")"
  if ! grep -Eq "^patch $name [^ ]+" "$root/UPSTREAM" 2>/dev/null; then
    echo "patch $name has no 'patch $name <upstream status>' line in UPSTREAM" >&2
    exit 1
  fi
done

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
src="$tmp/src"
mkdir "$src"
git -C "$src" init -q
git -C "$src" fetch -q --depth 1 "$url" "$commit"
git -C "$src" checkout -q FETCH_HEAD
actual="$(git -C "$src" rev-parse HEAD)"
if [ "$actual" != "$commit" ]; then
  echo "fetched $actual, expected $commit" >&2
  exit 1
fi
date="$(git -C "$src" log -1 --format=%cs)"

# Keep the patch lines: their status is hand-written.
patch_lines="$(grep -E '^patch ' "$root/UPSTREAM" 2>/dev/null || true)"

rm -rf "$dest"
mkdir -p "$dest/contrib/android" "$dest/contrib/msvc"
cp -R "$src/include" "$dest/include"
mkdir "$dest/src"
for f in "$src"/src/*.c "$src"/src/*.h "$src/src/libdivecomputer.symbols"; do
  cp "$f" "$dest/src/"
done
for f in COPYING NEWS README configure.ac; do
  cp "$src/$f" "$dest/$f"
done
cp "$src/contrib/android/Android.mk" "$dest/contrib/android/"
cp "$src/contrib/msvc/libdivecomputer.vcxproj" "$dest/contrib/msvc/"

if [ ${#patches[@]} -gt 0 ]; then
  for p in "${patches[@]}"; do
    if ! (cd "$dest" && git apply "$p"); then
      echo "patch $(basename "$p") no longer applies: if upstream merged it, delete it in this PR" >&2
      exit 1
    fi
  done
fi

# version.h: the .in file with the version from configure.ac.
define() {
  sed -n "s/^m4_define(\[dc_version_$1\],\[\([^]]*\)\])\$/\1/p" "$dest/configure.ac"
}
major="$(define major)"
minor="$(define minor)"
micro="$(define micro)"
suffix="$(define suffix)"
version="$major.$minor.$micro"
if [ -n "$suffix" ]; then
  version="$version-$suffix"
fi
mkdir -p "$root/native/include/libdivecomputer"
sed -e "s/@DC_VERSION@/$version/" \
    -e "s/@DC_VERSION_MAJOR@/$major/" \
    -e "s/@DC_VERSION_MINOR@/$minor/" \
    -e "s/@DC_VERSION_MICRO@/$micro/" \
    "$dest/include/libdivecomputer/version.h.in" \
    > "$root/native/include/libdivecomputer/version.h"
if grep -q '@' "$root/native/include/libdivecomputer/version.h"; then
  echo "version.h still has an unsubstituted @...@" >&2
  exit 1
fi
printf '#define DC_VERSION_REVISION "%s"\n' "$(printf '%s' "$commit" | cut -c1-7)" \
  > "$root/native/revision.h"

mkdir -p "$root/lib/src"
cat > "$root/lib/src/upstream.g.dart" <<DART
// GENERATED by tool/update_upstream.sh. Do not edit.

/// The upstream libdivecomputer commit that third_party/ is vendored from.
const String kLibdcPinnedCommit = '$commit';
DART

{
  echo "commit $commit"
  echo "date $date"
  echo "url $url"
  if [ -n "$patch_lines" ]; then
    printf '%s\n' "$patch_lines"
  else
    echo "patches none"
  fi
} > "$root/UPSTREAM"

if [ -n "${SKIP_FFIGEN:-}" ]; then
  echo "SKIP_FFIGEN set, skipping bindings"
elif [ -f "$root/ffigen.yaml" ]; then
  (cd "$root" && dart run ffigen)
else
  echo "ffigen.yaml not found, skipping bindings"
fi

echo "Vendored $commit ($date). Review the diff before committing."
